// `aion setup browser` — Track B dev Chrome bring-up in one command.
// Dry run by default (plan only, zero writes). With apply it writes ONLY
// B-owned files under the private Track B state dir plus ONE per-user host
// registration named com.aion.relay.dev. Track A (extension kgjfiel..., host
// com.aion.relay, Chrome Profile 3) is never read for writing or modified.
//
// The one step left to the owner: Chrome -> chrome://extensions -> Developer
// mode -> Load unpacked -> <extension_dir>, in the Track B dev profile.
import {createHash,generateKeyPairSync,createPublicKey} from 'node:crypto';
import {readFileSync,writeFileSync,mkdirSync,cpSync,existsSync,rmSync,chmodSync} from 'node:fs';
import {join,dirname,resolve} from 'node:path';
import {homedir} from 'node:os';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {createDevNativeManifest,DEV_HOST_NAME,validateDevIdentity} from '../native-host/guard.mjs';
import {verifyOwnedRegistration} from './registration.mjs';

const VELOCITY=resolve(dirname(fileURLToPath(import.meta.url)),'..','..');
const EXTENSION_SRC=resolve(VELOCITY,'..','extension');
const HOST_ENTRY=join(VELOCITY,'bin','aion-host-dev.mjs');
export const REGISTRY_KEY=`HKCU\\Software\\Google\\Chrome\\NativeMessagingHosts\\${DEV_HOST_NAME}`;

/** Chrome extension ID from the SPKI DER public key: sha256, first 16 bytes, hex 0-f -> a-p. */
export function extensionIdFromSpki(der){
  return [...createHash('sha256').update(der).digest().subarray(0,16).toString('hex')]
    .map(c=>String.fromCharCode(97+parseInt(c,16))).join('');
}
export function loadOrCreateDevKey(keyPath,{create=true}={}){
  let pem=existsSync(keyPath)?readFileSync(keyPath,'utf8'):null;
  if(!pem){
    if(!create)return null;
    pem=generateKeyPairSync('rsa',{modulusLength:2048}).privateKey.export({type:'pkcs8',format:'pem'});
    writeFileSync(keyPath,pem,{mode:0o600});try{chmodSync(keyPath,0o600);}catch{}
  }
  const der=createPublicKey(pem).export({type:'spki',format:'der'});
  return {manifestKey:der.toString('base64'),extensionId:extensionIdFromSpki(der)};
}
function userHostManifestDir(platform){
  if(platform==='linux')return join(homedir(),'.config','google-chrome','NativeMessagingHosts');
  if(platform==='darwin')return join(homedir(),'Library','Application Support','Google','Chrome','NativeMessagingHosts');
  return null; // win32: registry value points at the manifest in the state dir
}

export function planBrowserSetup({stateDir,platform=process.platform,nodeExe=process.execPath,userHostDir=null}){
  const extensionDir=join(stateDir,'extension-dev');
  const launcher=join(stateDir,platform==='win32'?'aion-host-dev.cmd':'aion-host-dev.sh');
  const hostManifest=join(stateDir,`${DEV_HOST_NAME}.json`);
  const userDir=userHostDir??userHostManifestDir(platform);
  return {schema:'aion.b.setup-plan/1',platform,stateDir,nodeExe,
    keyPath:join(stateDir,'dev-extension-key.pem'),configPath:join(stateDir,'host-dev.config.json'),
    extensionDir,launcher,hostManifest,
    registration:platform==='win32'?{kind:'registry',key:REGISTRY_KEY,value:hostManifest}
      :{kind:'file',path:join(userDir,`${DEV_HOST_NAME}.json`)},
    receipt:join(stateDir,'setup-receipt.json')};
}

function launcherText(plan){
  const cfg=plan.configPath;
  if(plan.platform==='win32')return ['@echo off','rem AION Track B dev native host launcher (com.aion.relay.dev). Generated by aion setup browser.',
    `"${plan.nodeExe}" "${HOST_ENTRY}" --config "${cfg}" %*`,'exit /b %ERRORLEVEL%',''].join('\r\n');
  return ['#!/bin/sh','# AION Track B dev native host launcher (com.aion.relay.dev). Generated by aion setup browser.',
    `exec "${plan.nodeExe}" "${HOST_ENTRY}" --config "${cfg}" "$@"`,''].join('\n');
}
export function buildDevExtension({extensionDir,manifestKey,source=EXTENSION_SRC}){
  rmSync(extensionDir,{recursive:true,force:true});
  mkdirSync(extensionDir,{recursive:true});
  cpSync(join(source,'src'),join(extensionDir,'src'),{recursive:true});
  mkdirSync(join(extensionDir,'src','dev'),{recursive:true});
  for(const f of ['dev-link.js','dev-worker.js'])cpSync(join(VELOCITY,'extension-dev',f),join(extensionDir,'src','dev',f));
  const m=JSON.parse(readFileSync(join(source,'manifest.json'),'utf8'));
  m.name='AION Relay Station (Track B dev)';
  m.description='AION Track B isolated development build. Talks only to com.aion.relay.dev.';
  m.key=manifestKey;
  m.background={service_worker:'src/dev/dev-worker.js',type:'module'};
  if(!m.permissions.includes('nativeMessaging'))m.permissions.push('nativeMessaging');
  writeFileSync(join(extensionDir,'manifest.json'),JSON.stringify(m,null,2)+'\n');
  return m;
}
function sourceSha(){
  const r=spawnSync('git',['rev-parse','HEAD'],{cwd:VELOCITY,encoding:'utf8',shell:false,windowsHide:true});
  return r.status===0?r.stdout.trim():null;
}

/** Apply the plan. `run` executes reg.exe on Windows (injectable for tests). */
export function applyBrowserSetup(plan,{run=spawnSync,now=()=>new Date()}={}){
  mkdirSync(plan.stateDir,{recursive:true,mode:0o700});
  const key=loadOrCreateDevKey(plan.keyPath);
  validateDevIdentity(key.extensionId); // refuses the Track A ID
  // Inspect the current GLOBAL registration BEFORE rewriting any manifest.
  // An existing registration belonging to a different dev key/path is foreign.
  verifyOwnedRegistration(plan,{run,expectedId:key.extensionId});
  buildDevExtension({extensionDir:plan.extensionDir,manifestKey:key.manifestKey});
  writeFileSync(plan.configPath,JSON.stringify({schema:'aion.b.host-config/1',extension_id:key.extensionId,state_dir:plan.stateDir},null,2),{mode:0o600});
  writeFileSync(plan.launcher,launcherText(plan),{mode:0o700});
  if(plan.platform!=='win32')chmodSync(plan.launcher,0o700);
  const manifest=createDevNativeManifest({expectedExtensionId:key.extensionId,hostExecutablePath:plan.launcher});
  writeFileSync(plan.hostManifest,JSON.stringify(manifest,null,2)+'\n');
  if(plan.registration.kind==='registry'){
    const r=run('reg',['add',plan.registration.key,'/ve','/t','REG_SZ','/d',plan.registration.value,'/f'],
      {encoding:'utf8',shell:false,windowsHide:true,timeout:10000});
    if(r.error||r.status!==0)throw Object.assign(new Error('reg add failed'),{code:'HOST_REGISTRATION_FAILED'});
  }else{
    mkdirSync(dirname(plan.registration.path),{recursive:true});
    writeFileSync(plan.registration.path,JSON.stringify(manifest,null,2)+'\n');
  }
  const receipt={schema:'aion.b.setup-receipt/1',at_utc:now().toISOString(),source_sha:sourceSha(),
    extension_id:key.extensionId,host:DEV_HOST_NAME,extension_dir:plan.extensionDir,
    host_manifest:plan.hostManifest,registration:plan.registration,track_a_touched:false,
    owner_next_step:`chrome://extensions -> Developer mode -> Load unpacked -> ${plan.extensionDir} (Track B dev profile only)`};
  writeFileSync(plan.receipt,JSON.stringify(receipt,null,2)+'\n');
  return receipt;
}

/** Remove ONLY the B host registration and generated files. Ledger and key are kept. */
export function uninstallBrowserSetup(plan,{run=spawnSync}={}){
  // Uninstall is not an indiscriminate 'reg delete' or 'rm -rf'. Require the
  // receipt and pinned dev extension identity written by *this* installer.
  let receipt;
  try{receipt=JSON.parse(readFileSync(plan.receipt,'utf8'));}
  catch{throw Object.assign(new Error('B setup receipt missing'),{code:'OWNERSHIP_RECEIPT_MISSING'});}
  const key=loadOrCreateDevKey(plan.keyPath,{create:false});
  if(!key||receipt?.schema!=='aion.b.setup-receipt/1'
    ||receipt.extension_id!==key.extensionId || receipt.host!==DEV_HOST_NAME
    ||receipt.extension_dir!==plan.extensionDir || receipt.host_manifest!==plan.hostManifest
    ||receipt.registration?.kind!==plan.registration.kind)
    throw Object.assign(new Error('B setup ownership mismatch'),{code:'OWNERSHIP_RECEIPT_MISMATCH'});
  const owned=verifyOwnedRegistration(plan,{run,expectedId:key.extensionId});
  if(!owned.exists)
    throw Object.assign(new Error('dev host registration no longer exists'),{code:'REGISTRATION_NOT_FOUND'});
  let config,built;
  try{
    config=JSON.parse(readFileSync(plan.configPath,'utf8'));
    built=JSON.parse(readFileSync(join(plan.extensionDir,'manifest.json'),'utf8'));
  }catch{throw Object.assign(new Error('dev install files changed or missing'),{code:'OWNERSHIP_FILES_UNVERIFIED'});}
  if(config?.extension_id!==key.extensionId || config?.state_dir!==plan.stateDir
    ||built?.key!==key.manifestKey || built?.background?.service_worker!=='src/dev/dev-worker.js')
    throw Object.assign(new Error('dev install files differ'),{code:'OWNERSHIP_FILES_UNVERIFIED'});
  const removed=[];
  if(plan.registration.kind==='registry'){
    const r=run('reg',['delete',plan.registration.key,'/f'],{encoding:'utf8',shell:false,windowsHide:true,timeout:10000});
    if(r.error||r.status!==0)
      throw Object.assign(new Error('dev host removal failed'),{code:'REGISTRATION_REMOVAL_FAILED'});
    removed.push({registry:plan.registration.key,ok:true});
  }else{
    rmSync(plan.registration.path);removed.push({file:plan.registration.path});
  }
  for(const p of [plan.hostManifest,plan.launcher,plan.configPath])if(existsSync(p)){rmSync(p);removed.push({file:p});}
  if(existsSync(plan.extensionDir)){rmSync(plan.extensionDir,{recursive:true});removed.push({dir:plan.extensionDir});}
  return {schema:'aion.b.uninstall/1',removed,kept:['bus.json','dev-extension-key.pem'],track_a_touched:false};
}
